-- ------------------------------------------------------------
-- 3. Bucket de imágenes
-- ------------------------------------------------------------
-- Público: las capturas se muestran con getPublicUrl(), sin URL firmada.

insert into storage.buckets (id, name, public)
values ('manual', 'manual', true)
on conflict (id) do update set public = true;

-- storage.objects sí tiene RLS activo, así que hacen falta políticas.
-- El frontend sube con la publishable key (rol anon), igual que antropometrías.

drop policy if exists "manual lectura publica"  on storage.objects;
drop policy if exists "manual subida"           on storage.objects;
drop policy if exists "manual actualizacion"    on storage.objects;
drop policy if exists "manual borrado"          on storage.objects;

create policy "manual lectura publica" on storage.objects
  for select using (bucket_id = 'manual');

create policy "manual subida" on storage.objects
  for insert with check (bucket_id = 'manual');

create policy "manual actualizacion" on storage.objects
  for update using (bucket_id = 'manual');

create policy "manual borrado" on storage.objects
  for delete using (bucket_id = 'manual');
