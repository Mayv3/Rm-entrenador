create table if not exists public.manual_capitulos (
  id           bigint generated by default as identity primary key,
  orden        integer      not null default 1,
  eyebrow      text,
  titulo       text         not null default '',
  resumen      text,
  -- URL pública de la captura: del bucket "manual" o un asset estático (/manual/...)
  imagen_url   text,
  -- Ruta dentro del bucket. null cuando imagen_url es un asset estático del repo.
  imagen_path  text,
  created_at   timestamptz  not null default now(),
  updated_at   timestamptz  not null default now()
);

create table if not exists public.manual_pasos (
  id           bigint generated by default as identity primary key,
  capitulo_id  bigint       not null references public.manual_capitulos(id) on delete cascade,
  orden        integer      not null default 1,
  titulo       text         not null default '',
  texto        text         not null default '',
  created_at   timestamptz  not null default now()
);

create index if not exists manual_capitulos_orden_idx on public.manual_capitulos (orden);
create index if not exists manual_pasos_capitulo_idx  on public.manual_pasos (capitulo_id, orden);

-- updated_at automático en capítulos
create or replace function public.manual_capitulos_touch()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists manual_capitulos_touch_trg on public.manual_capitulos;
create trigger manual_capitulos_touch_trg
  before update on public.manual_capitulos
  for each row execute function public.manual_capitulos_touch();

